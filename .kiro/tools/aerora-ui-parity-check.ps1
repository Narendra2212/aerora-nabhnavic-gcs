#!/usr/bin/env pwsh
# Declaration / definition parity for the Aerora UI module, by text analysis.
#
# A substitute for a compiler, not a replacement for one (D-006). It answers one question: does
# every ClassName:: definition in a .cc have a same-named declaration in its .h, and does every
# declaration have a definition somewhere.
#
# Usage:  powershell -NoProfile -ExecutionPolicy Bypass -File .kiro/tools/aerora-ui-parity-check.ps1

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$problems = 0

$units = @(
    'aerora/src/UI/AeroraQmlOverrides|AeroraQmlOverrides'
    'aerora/src/UI/AeroraVehicleUiContext|AeroraVehicleUiContext'
    'aerora/test/UI/AeroraUiFoundationTest|AeroraUiFoundationTest'
    'aerora/test/UI/AeroraUiSafetyTest|AeroraUiSafetyTest'
)

foreach ($unit in $units) {
    $parts = $unit.Split('|')
    $stem = $parts[0]
    $cls = $parts[1]

    $headerPath = Join-Path $root ($stem + '.h')
    $sourcePath = Join-Path $root ($stem + '.cc')
    $header = [System.IO.File]::ReadAllText($headerPath)
    $source = [System.IO.File]::ReadAllText($sourcePath)

    Write-Output ("=== {0} ===" -f $cls)

    # Definitions: every "Cls::name(" in the .cc.
    $defs = New-Object System.Collections.Generic.List[string]
    foreach ($m in [regex]::Matches($source, [regex]::Escape($cls) + '::(~?[A-Za-z_][A-Za-z0-9_]*)\s*\(')) {
        $name = $m.Groups[1].Value
        if (-not $defs.Contains($name)) { [void]$defs.Add($name) }
    }

    foreach ($name in $defs) {
        if ($name -eq $cls -or $name -eq ('~' + $cls)) {
            Write-Output ("  OK (ctor/dtor)  {0}" -f $name)
            continue
        }
        # The declaration must mention the name followed by an open paren, outside a comment line.
        $found = $false
        foreach ($line in $header.Split([char]10)) {
            $clean = $line.Trim()
            if ($clean.StartsWith('///') -or $clean.StartsWith('//') -or $clean.StartsWith('*')) { continue }
            if ($clean -match ('\b' + [regex]::Escape($name) + '\s*\(')) { $found = $true; break }
        }
        if ($found) {
            Write-Output ("  OK              {0}" -f $name)
        } else {
            Write-Output ("  NO DECLARATION  {0}" -f $name)
            $problems++
        }
    }

    # Declarations: non-inline prototypes in the .h must have a definition in the .cc.
    foreach ($line in $header.Split([char]10)) {
        $clean = $line.Trim()
        if ($clean.StartsWith('///') -or $clean.StartsWith('//') -or $clean.StartsWith('*')) { continue }
        if ($clean.StartsWith('Q_')) { continue }
        # A prototype ends in ");" and carries no body.
        if ($clean -notmatch '^(?:\[\[nodiscard\]\]\s*)?(?:static\s+|virtual\s+|explicit\s+)*[A-Za-z_][A-Za-z0-9_:<>,\*&\s]*?\b([a-zA-Z_][A-Za-z0-9_]*)\s*\([^;{]*\)\s*(?:const\s*)?(?:noexcept\s*)?(?:override\s*)?(?:final\s*)?;\s*$') {
            continue
        }
        $name = $Matches[1]
        if ($name -eq $cls -or $name -eq ('~' + $cls)) { continue }
        if ($defs.Contains($name)) { continue }
        # Signals and slots are generated by moc or defined by it; signals have no body.
        Write-Output ("  CHECK           {0}  (declared, no Cls:: definition - signal, moc-generated or inline?)" -f $name)
    }
}

Write-Output ''
Write-Output ("parity problems: {0}" -f $problems)
Write-Output 'NOTE: text analysis. Overload sets and signatures are NOT compared; only names.'
exit ([int]($problems -gt 0))
